#!/usr/bin/env node
/**
 * CODEGEN — emit the client's names-only command allow-list from the secret registry.
 *
 * The full registry (names + summaries + param specs) is the crown jewel and lives
 * server-side in `proxy/src/secrets/command-params.ts`. But command NAMES are not
 * secret (they leak as tool_use names anyway) and the client's dispatch guard
 * (`server/ai/src/agent/executeTool.ts`) needs them at runtime in EVERY build — incl.
 * the stripped prod binary. So we generate a names-only mirror into `server/ai`.
 *
 * Single source of truth = command-params.ts. This derivative can't drift: the
 * drift-guard test re-runs this generator and asserts the committed file is identical.
 *
 * Run:  node proxy/scripts/gen-command-names.mjs        (writes the file)
 *       node proxy/scripts/gen-command-names.mjs --check (CI/drift: exit 1 if stale)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const REGISTRY = join(here, '..', 'src', 'secrets', 'command-params.ts');
const OUT = join(here, '..', '..', 'server', 'ai', 'src', 'tools', 'command-names.generated.ts');

/** Parse the COMMAND_PARAMS object: top-level keys (2-space indent) = command names;
 *  a `internal: true` inside an entry's block flags it as hidden-from-model. */
function parseRegistry(src) {
  const keyRe = /^ {2}(\w+): \{/gm;
  const matches = [...src.matchAll(keyRe)];
  if (matches.length === 0) throw new Error('gen-command-names: no command entries found — registry format changed?');
  const names = [];
  const internal = [];
  for (let i = 0; i < matches.length; i++) {
    const name = matches[i][1];
    const start = matches[i].index;
    const end = i + 1 < matches.length ? matches[i + 1].index : src.length;
    const block = src.slice(start, end);
    names.push(name);
    if (/\binternal:\s*true\b/.test(block)) internal.push(name);
  }
  return { names, internal };
}

function render({ names, internal }) {
  const namesLines = names.map((n) => `  '${n}',`).join('\n');
  const internalLines = internal.map((n) => `  '${n}',`).join('\n');
  return `// AUTO-GENERATED by proxy/scripts/gen-command-names.mjs — DO NOT EDIT BY HAND.
//
// Names-only mirror of the secret registry (proxy/src/secrets/command-params.ts).
// Command names are NOT secret — they leak as tool_use names — so they ship in the
// binary and back the client-side dispatch guard. The catalog summaries + param
// specs + system prompt stay server-side in the Worker and never ship here.
//
// Regenerate: \`node proxy/scripts/gen-command-names.mjs\`. The drift-guard test
// fails if this file is stale relative to the registry.

/** Every command name in the registry (incl. internal + batch), registry order. */
export const COMMAND_NAMES = [
${namesLines}
] as const;

export type CommandName = (typeof COMMAND_NAMES)[number];

/** Subset flagged \`internal: true\` — kept in the registry but hidden from the model;
 *  the dispatch guard rejects these even if the model guesses the raw name. */
export const INTERNAL_COMMANDS: ReadonlySet<string> = new Set([
${internalLines}
]);
`;
}

const src = readFileSync(REGISTRY, 'utf8');
const parsed = parseRegistry(src);
const out = render(parsed);

const check = process.argv.includes('--check');
if (check) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch { /* missing → stale */ }
  if (current !== out) {
    console.error('command-names.generated.ts is STALE — run: node proxy/scripts/gen-command-names.mjs');
    process.exit(1);
  }
  console.log(`command-names.generated.ts up to date (${parsed.names.length} names, ${parsed.internal.length} internal).`);
} else {
  writeFileSync(OUT, out);
  console.log(`Wrote ${OUT} (${parsed.names.length} names, ${parsed.internal.length} internal).`);
}
